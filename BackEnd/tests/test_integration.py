import os
import time
import json
import requests
import pika
import pytest

BASE_URL = os.environ.get("TEST_BASE_URL", "http://localhost:8000")
RABBITMQ_HOST = os.environ.get("RABBITMQ_HOST", "rabbitmq")
QUEUE_NAME = "ticket_pdf_queue"
PDF_DIR = "/app/pdfs"

def test_rabbitmq_connection():
    try:
        connection = pika.BlockingConnection(
            pika.ConnectionParameters(host=RABBITMQ_HOST, socket_timeout=5)
        )
        channel = connection.channel()
        channel.queue_declare(queue=QUEUE_NAME, durable=True)
        connection.close()
        assert True
    except Exception as e:
        pytest.fail(f"Could not connect to RabbitMQ: {e}")

def test_pdf_generation_e2e():
    test_ticket_id = 9999
    payload = {
        "ticket_id": test_ticket_id,
        "passenger_name": "Test Integration User",
        "flight_number": "LO-500",
        "seat": "12A"
    }

    connection = pika.BlockingConnection(pika.ConnectionParameters(host=RABBITMQ_HOST))
    channel = connection.channel()
    channel.queue_declare(queue=QUEUE_NAME, durable=True)
    channel.basic_publish(
        exchange='',
        routing_key=QUEUE_NAME,
        body=json.dumps(payload),
        properties=pika.BasicProperties(delivery_mode=2)
    )
    connection.close()

    expected_file = os.path.join(PDF_DIR, f"ticket_{test_ticket_id}.pdf")
    file_created = False
    
    for _ in range(14):
        if os.path.exists(expected_file):
            file_created = True
            break
        time.sleep(0.5)

    assert file_created, f"File {expected_file} was not generated by pdf_worker!"

    response = requests.get(f"{BASE_URL}/tickets/{test_ticket_id}/pdf")
    assert response.status_code == 200
    assert response.headers["content-type"] == "application/pdf"
    assert len(response.content) > 0

    if os.path.exists(expected_file):
        os.remove(expected_file)
